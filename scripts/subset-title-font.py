"""Optional: regenerate the bundled title font after changing Chinese headings.

Requires npm install, then: python3 -m pip install 'fonttools[woff]' brotli
Run: python3 scripts/subset-title-font.py
Normal development and production builds do not require Python.
"""
from pathlib import Path
from shutil import copyfile

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parents[1]
source = root / 'node_modules/@fontsource-variable/noto-serif-sc'
target = root / 'src/fonts'
target.mkdir(exist_ok=True)
characters = set(map(ord, '让想法，有处可去。连接你的模型'))
remaining = set(characters)
rules = []

for path in sorted((source / 'files').glob('noto-serif-sc-*-wght-normal.woff2')):
    font = TTFont(path)
    needed = remaining.intersection(font.getBestCmap())
    if not needed:
        font.close()
        continue
    font = instantiateVariableFont(font, {'wght': 400}, inplace=True)
    options = subset.Options()
    options.flavor = 'woff2'
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=needed)
    subsetter.subset(font)
    name = f'title-{len(rules)}.woff2'
    font.save(target / name)
    font.close()
    ranges = ', '.join(f'U+{code:X}' for code in sorted(needed))
    rules.append(f"@font-face {{\n  font-family: 'Astra Serif';\n  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n  src: url('./{name}') format('woff2');\n  unicode-range: {ranges};\n}}")
    remaining -= needed
    if not remaining:
        break

if remaining:
    raise RuntimeError(f'Missing characters: {remaining}')
(target / 'title.css').write_text('/* Noto Serif SC subset. See OFL.txt. Generated by scripts/subset-title-font.py. */\n' + '\n'.join(rules) + '\n')
copyfile(source / 'LICENSE', target / 'OFL.txt')
licenses = root / 'public/font-licenses'
licenses.mkdir(exist_ok=True)
copyfile(source / 'LICENSE', licenses / 'noto-serif-sc.txt')
copyfile(root / 'node_modules/@fontsource-variable/inter/LICENSE', licenses / 'inter.txt')
print(f'Generated {len(rules)} subsets, {sum(p.stat().st_size for p in target.glob("*.woff2")):,} bytes.')
